import {test,expect} from '@playwright/test';
test('benefits are shown first and filters preserve uncertainty',async({page})=>{
 await page.goto('/');
 await expect(page.getByRole('heading',{name:'진주에서, 탄소중립 실천할 곳을 찾아요.'})).toBeVisible();
 await expect(page.locator('.benefit-card')).toHaveCount(6);
 await expect(page.locator('.benefit-card').first()).toContainText('400원 할인');
 await expect(page.locator('.benefit-card').first()).toContainText('지점 재확인 필요');
 await expect(page.locator('.map-panel')).toHaveCount(0);
 await page.evaluate(()=>document.fonts.ready);
 await page.screenshot({path:`/tmp/tumbler-benefits-${test.info().project.name}.png`,fullPage:true});
 await page.getByRole('button',{name:'즉시 할인',exact:true}).click();
 await expect(page.locator('.benefit-card')).toHaveCount(2);
 await expect(page.locator('.benefit-grid')).toContainText('할인 금액 확인 중');
 await page.getByRole('button',{name:'포인트 적립',exact:true}).click();
 await expect(page.locator('.benefit-card')).toHaveCount(2);
 await expect(page.locator('.benefit-grid')).toContainText('메가MGC커피');
 await page.getByLabel('매장명 또는 주소 검색').fill('없는매장');
 await expect(page.getByText('검색 결과가 없어요')).toBeVisible();
 await page.getByRole('button',{name:'필터 초기화'}).click();
 await expect(page.locator('.benefit-card')).toHaveCount(6);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
test('details show benefit, conditions and collapsible research',async({page})=>{
 await page.goto('/');
 await page.getByRole('button',{name:/이용 조건 보기/}).click();
 const dialog=page.getByRole('dialog');
 await expect(dialog.locator('.detail-benefit')).toContainText('400원 할인');
 await expect(dialog.locator('.detail-benefit')).toContainText('개인컵 할인 또는 에코별 선택');
 await expect(dialog.getByText('현장 방문·전화 확인',{exact:true})).not.toBeVisible();
 await dialog.locator('summary').click();
 await expect(dialog).toContainText('미실시');
 await expect(dialog.getByRole('link',{name:/첨부 조사보고서/})).toHaveAttribute('href','/research/report.pdf#page=4');
 await page.keyboard.press('Escape');
 await expect(dialog).toHaveCount(0);
});
test('map opens on demand and practice sections remain visible while scrolling',async({page})=>{
 await page.goto('/');
 await page.getByRole('button',{name:'지도 보기',exact:true}).click();
 await expect(page.locator('.map-panel')).toBeVisible();
 await page.getByRole('button',{name:'지도 접기',exact:true}).click();
 await expect(page.locator('.map-panel')).toHaveCount(0);
 await expect(page.locator('#mobility .practice-store')).toHaveCount(2);
 await expect(page.locator('#everyday .practice-store')).toHaveCount(4);
 await page.getByRole('link',{name:/자전거 · 바이크/}).click();
 await expect(page).toHaveURL(/#mobility$/);
 await expect(page.getByRole('heading',{name:/자전거·바이크, 두 바퀴의 실천/})).toBeInViewport();
 await page.getByRole('link',{name:/자원순환 · 수선/}).click();
 await expect(page).toHaveURL(/#everyday$/);
 await expect(page.getByRole('heading',{name:/자원순환·수선, 한 번 더 쓰는 생활/})).toBeInViewport();
 await page.locator('.other-store').filter({hasText:'한살림'}).click();
 await expect(page.getByRole('dialog')).toContainText('500원/건');
});
