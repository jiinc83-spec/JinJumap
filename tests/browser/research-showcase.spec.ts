import {test,expect} from '@playwright/test';
test('three research UIs preserve evidence and uncertainty without external connections',async({page})=>{
 const external:string[]=[];
 page.on('request',r=>{if(!['localhost','127.0.0.1'].includes(new URL(r.url()).hostname))external.push(new URL(r.url()).hostname);});
 await page.goto('/?preview=research');
 await expect(page.getByRole('heading',{name:/오늘의 작은 행동/})).toBeVisible();
 await expect(page.locator('.research-place-card')).toHaveCount(13);
 await page.getByLabel('개인컵·다회용기 이용 여부를 모르는 문의 대상 9곳도 보기').check();
 await expect(page.locator('.research-place-card')).toHaveCount(22);
 await page.getByRole('button',{name:'매장 문의 후보',exact:true}).click();
 await expect(page.locator('.research-place-card')).toHaveCount(9);
 await page.locator('.research-place-card').first().click();
 await expect(page.getByRole('dialog')).toContainText('개인컵·다회용기 이용 가능 여부와 혜택은 확인되지 않았습니다');
 await expect(page.getByRole('dialog')).toContainText('현장 검증 미기재');
 await page.keyboard.press('Escape');
 await page.getByRole('button',{name:/B남강에서 걷기|B 남강에서 걷기/}).click();
 await expect(page.locator('.research-place-card')).toHaveCount(7);
 await page.getByRole('button',{name:'자전거',exact:true}).click();
 await expect(page.locator('.research-place-card')).toHaveCount(3);
 await page.getByLabel('조사 장소 검색').fill('칠암동');
 await expect(page.locator('.research-place-card')).toHaveCount(1);
 await page.locator('.research-place-card').click();
 await expect(page.getByRole('dialog')).toContainText('경상남도 진주시 칠암동 1');
 await expect(page.getByRole('dialog')).toContainText('미기재 · 핀 미표시');
 await page.keyboard.press('Escape');
 await page.getByRole('button',{name:/C근거로 살펴보기|C 근거로 살펴보기/}).click();
 await expect(page.locator('.research-evidence-row')).toHaveCount(22);
 await page.getByLabel('조사 권역').selectOption('대안동 조사권역');
 await expect(page.locator('.research-evidence-row')).toHaveCount(15);
 await page.getByLabel('조사 장소 검색').fill('없는장소');
 await expect(page.getByText('조건에 맞는 조사 기록이 없어요')).toBeVisible();
 await page.getByRole('button',{name:'필터 초기화'}).click();
 await expect(page.locator('.research-evidence-row')).toHaveCount(22);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 expect(external).toEqual([]);
});
test('brand memos stay separate from confirmed local benefits',async({page})=>{
 await page.goto('/?preview=research');
 await page.getByRole('button',{name:/텀블러 할인점 찾기/}).click();
 await expect(page.getByRole('dialog')).toContainText('지점명·기준일·현재 적용 여부는 확인되지 않았습니다');
 await expect(page.locator('.research-policies>div')).toHaveCount(10);
 await expect(page.getByRole('dialog')).toContainText('1회 300원, 다음 달 환급');
 await expect(page.getByRole('dialog')).toContainText('확정 혜택으로 표시하지 않습니다');
 await page.keyboard.press('Escape');
 await page.getByRole('button',{name:'조사자료',exact:true}).click();
 await expect(page.getByRole('dialog')).toContainText('지역 전체에 시설이 없다는 확정 사실로 일반화하지 않았습니다');
});
